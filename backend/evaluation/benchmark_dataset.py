"""Curated 60+ query interview-domain evaluation benchmark dataset."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass
class BenchmarkTestCase:
    """A structured benchmark test case with ground-truth labels."""

    id: str
    query: str
    category: str
    expected_route: str
    expected_company: str | None = None
    expected_topics: list[str] = field(default_factory=list)
    relevant_doc_identifiers: list[str] = field(default_factory=list)
    expected_hop_count: int = 1
    should_abstain: bool = False
    expected_answer_keywords: list[str] = field(default_factory=list)
    notes: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "query": self.query,
            "category": self.category,
            "expected_route": self.expected_route,
            "expected_company": self.expected_company,
            "expected_topics": self.expected_topics,
            "relevant_doc_identifiers": self.relevant_doc_identifiers,
            "expected_hop_count": self.expected_hop_count,
            "should_abstain": self.should_abstain,
            "expected_answer_keywords": self.expected_answer_keywords,
            "notes": self.notes,
        }


